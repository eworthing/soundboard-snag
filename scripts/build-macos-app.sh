#!/bin/bash
# Build "Soundboard Snag.app", a double-clickable macOS app, in this folder.
#
# The app is a small launcher that runs soundboard-snag.py with a private
# virtualenv (.venv) holding the window libraries from requirements.txt. It
# bakes in absolute paths at build time (apps launched from Finder get a
# stripped PATH). Re-run this script after moving the repo or upgrading Python.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
PY="$(command -v python3 || true)"
[ -n "$PY" ] || { echo "error: python3 not found on PATH" >&2; exit 1; }
[ -f "$REPO/soundboard-snag.py" ] || { echo "error: soundboard-snag.py not found in $REPO" >&2; exit 1; }
"$PY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' \
  || { echo "error: Python 3.9+ required ($PY is older)" >&2; exit 1; }

VENV="$REPO/.venv"
if [ ! -x "$VENV/bin/python" ]; then
  echo "Creating $VENV ..."
  "$PY" -m venv "$VENV"
fi
echo "Installing window libraries ..."
"$VENV/bin/python" -m pip install --quiet --upgrade pip
"$VENV/bin/python" -m pip install --quiet -r "$REPO/requirements.txt"

APP="$REPO/Soundboard Snag.app"
MACOS="$APP/Contents/MacOS"
rm -rf "$APP"
mkdir -p "$MACOS" "$APP/Contents/Resources"
cp "$REPO/assets/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Soundboard Snag</string>
  <key>CFBundleDisplayName</key><string>Soundboard Snag</string>
  <key>CFBundleIdentifier</key><string>com.soundboardsnag.app</string>
  <key>CFBundleVersion</key><string>2.0</string>
  <key>CFBundleShortVersionString</key><string>2.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>launcher</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>11.3</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$MACOS/launcher" <<LAUNCHER
#!/bin/bash
# Generated by scripts/build-macos-app.sh; re-run the build instead of editing.
cd "$REPO" || exit 1
exec "$VENV/bin/python" soundboard-snag.py
LAUNCHER
chmod +x "$MACOS/launcher"

echo "Built: $APP"
echo "Double-click it in Finder, or run: open \"$APP\""
